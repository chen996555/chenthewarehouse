// 已收录公司精确映射（读 companies.js，100% 准；companies.js 是纯数据，无循环依赖）
let KNOWN = null;
function knownGroup(name) {
  if (!KNOWN) {
    try {
      const { COMPANIES } = require('./companies');
      KNOWN = new Map(COMPANIES.map((c) => [c.name, c.group]));
    } catch { KNOWN = new Map(); }
  }
  return KNOWN.get(name);
}

function classifyGroup(name) {
  const n = String(name || '').replace(/\s+/g, '');
  if (!n) return '互联网';
  const known = knownGroup(n);
  if (known) return known; // 已收录公司精确匹配，优先
  for (const [group, kws] of RULES) {
    if (kws.some((k) => n.includes(k))) return group;
  }
  return '互联网'; // 兜底：品牌名新公司，需候选清单带 group 或人工确认
}

module.exports = { classifyGroup, RULES };
